@tool
def bom_query_tool(
    operation: Literal[
        "summary", "filter", "lookup",
        "quantity", "ambiguities", "validation_issues"
    ],
    search_term: str | None = None,
    production_quantity: int | None = None,
    *,
    runtime: ToolRuntime
) -> dict:
    """Query the BOM uploaded in the current conversation.

    Operations:
    - summary: Count BOM items and component categories.
    - filter: Find components by description, category, or manufacturer.
    - lookup: Check whether an exact MPN exists.
    - quantity: Calculate required units for a production volume.
    - ambiguities: Find rows with multiple MPN/manufacturer candidates.
    - validation_issues: Retrieve parsing warnings and errors.

    For filter, lookup, and quantity, provide search_term.
    For quantity, also provide production_quantity.
    """

    # ToolRuntime is injected by LangGraph, not generated by llm.
    thread_id = runtime.config["configurable"]["thread_id"]

    # Execute our existing deterministic Python BOM query.
    return bom_query(
        operation=operation,
        thread_id=thread_id,
        search_term=search_term,
        production_quantity=production_quantity
    )


@tool
def procure_tool(assemblies: int, *, runtime: ToolRuntime) -> dict:
    """Analyze procurement for the uploaded BOM: fetch live Mouser and DigiKey
    stock/prices/lead times, calculate assembly coverage, component shortages,
    lifecycle/MOQ risk and production blockers for the requested assembly count.
    Use for ALL supplier sourcing, availability, coverage and risk questions.
    Displays live results in Streamlit without persisting supplier data.
    """
    thread_id = runtime.config["configurable"]["thread_id"]
    try:
        # LangGraph custom stream events are emitted during the synchronous tool,
        # without storing supplier data in checkpointed messages.
        writer = get_stream_writer()
        def emit(stage, **counts):
            writer({"kind": "procurement_progress", "stage": stage, **counts})
        source_thread(thread_id, assemblies, progress=emit)
        # No supplier or derived report data is returned to ToolNode/checkpointer.
        # The summary node reads the in-memory report directly after this tool.
        return {"status": "ready", "message": "Live procurement analysis completed."}
    except Exception:
        return {"status": "error", "message": "Live sourcing failed; check BOM and API configuration."}


ALL_TOOLS = [bom_query_tool, procure_tool]

llm = ChatGoogleGenerativeAI(model = "gemini-3.5-flash-lite")

from langchain_core.messages import SystemMessage

BOM_INSTRUCTIONS = """You are an electronics BOM assistant.
Use bom_query_tool for the uploaded BOM. Use procure_tool for live supplier
availability, shortages, stock coverage, purchasing and procurement risk.
The procurement tool returns a completion marker; a dedicated tool-free
summary node explains calculated results. Do not re-run procurement after
it completes. Answer permitted general electronics questions and greetings.
Never disclose credentials, invent supplier information or approve substitutions.
"""

INTENT_INSTRUCTIONS = """You are a query-scope guardrail for an electronics BOM chatbot.
Classify the latest user request using relevant conversation context.
Return OUT_OF_SCOPE only for clearly unrelated requests (politics, sports,
entertainment, etc.). Return UNSAFE for requests to reveal secrets or bypass
access controls. Return ALLOWED for BOM queries, sourcing, procurement risks,
electronics engineering, greetings, and relevant follow-up questions.
When uncertain whether a request belongs to the electronics project, ALLOW it.
This decision never chooses a tool or determines an answer. Only classify scope.
"""

class IntentResult(BaseModel):
    intent: Literal["ALLOWED", "OUT_OF_SCOPE", "UNSAFE"]

intent_llm = llm.with_structured_output(IntentResult)


class ChatState(TypedDict, total=False):
    messages: Annotated[list[BaseMessage], add_messages]
    intent: str
    guardrail_reply: str

# Preserve the ORIGINAL model-driven tool selection.
llm_with_tools = llm.bind_tools(ALL_TOOLS)


def intent_node(state: ChatState):
    """Scope/safety screening only; NEVER chooses procurement or BOM tools."""
    latest = next((m for m in reversed(state["messages"]) if isinstance(m, HumanMessage)), None)
    blocked = basic_query_check(latest.content if latest else None)
    if blocked:
        return {"intent": "BLOCKED", "guardrail_reply": blocked}
    try:
        # Only the user's recent questions; do not send previous supplier results.
        recent = [m for m in state["messages"] if isinstance(m, HumanMessage)][-4:]
        decision = intent_llm.invoke([SystemMessage(content=INTENT_INSTRUCTIONS), *recent])
        intent, reply = route_intent(decision.intent)
        return {"intent": intent, "guardrail_reply": reply or ""}
    except Exception:
        # Classifier outage should not block legitimate user queries.
        return {"intent": "ALLOWED", "guardrail_reply": ""}


def route_by_intent(state: ChatState) -> str:
    return "scope_reply" if state.get("intent") in ("OUT_OF_SCOPE", "UNSAFE", "BLOCKED") else "chat_node"


def scope_reply(state: ChatState):
    return {"messages": [AIMessage(content=state.get("guardrail_reply") or "I can help with electronics BOM analysis and procurement questions.")]}


def chat_node(state: ChatState):
    """Allow multi-tool turns while enforcing a shared, bounded execution policy."""
    messages = [SystemMessage(content=BOM_INSTRUCTIONS), *state["messages"]]
    response = llm_with_tools.invoke(messages)
    proposed_calls = response.tool_calls or []
    if proposed_calls:
        allowed, reason = check_tool_budget(state["messages"], proposed_calls)
        if not allowed:
            # Never append rejected tool calls to graph state: that would leave
            # unresolved tool_call IDs and break the conversation protocol.
            final = llm.invoke([
                SystemMessage(content=(
                    "Answer the user's latest question from already available "
                    "information. Do not call tools. Be candid about incomplete "
                    "or failed operations; never invent procurement data. "
                    "Tool execution was stopped: " + reason
                )),
                *state["messages"],
            ])
            return {"messages": [final]}
    return {"messages": [response]}


def route_after_tools(state: ChatState) -> str:
    """Procurement tool finishes at a tool-free summary node; other tools resume chat."""
    for message in reversed(state["messages"]):
        if not isinstance(message, ToolMessage):
            break
        if message.name == "procure_tool":
            return "summary_node"
    return "chat_node"


def summary_node(state: ChatState, config):
    """Summarize transient derived findings; no supplier evidence in graph state."""
    thread_id = config["configurable"]["thread_id"]
    tool_result = next(
        (m for m in reversed(state["messages"])
         if isinstance(m, ToolMessage) and m.name == "procure_tool"), None
    )
    try:
        payload = json.loads(tool_result.content) if tool_result is not None and isinstance(tool_result.content, str) else (tool_result.content if tool_result is not None else {})
    except (ValueError, TypeError):
        payload = {}
    if payload.get("status") != "ready":
        return {"messages": [AIMessage(content=payload.get("message", "Procurement analysis could not be completed."))]}

    # Only derived, compact data from the current run is sent to Gemini.
    # No tool-enabled model is invoked here, so it cannot start another API run.
    evidence = narrative_evidence(thread_id)
    if evidence is None:
        return {"messages": [AIMessage(content="The analysis completed, but its temporary summary evidence is unavailable. See the live report panel.")]}
    try:
        writer = get_stream_writer()
        writer({"kind": "procurement_progress", "stage": "summary_started"})
        user_question = next(
            (m.content for m in reversed(state["messages"]) if isinstance(m, HumanMessage)),
            "Summarize procurement analysis"
        )
        system_prompt = """You are an electronics procurement and supply-risk analyst.
Answer the user's exact question using only the provided structured evidence.
Explain relevant results clearly and proportionately, including limits or uncertainties.
Do not invent supplier facts, quantities, approved substitutions or delivery guarantees.
Unknown inventory does not mean zero stock. Do not claim confirmed shortages
where the evidence marks the gap unconfirmed. Keep the answer focused.
"""
        response = llm.invoke([
            SystemMessage(content=system_prompt),
            HumanMessage(content="USER QUESTION:\n" + str(user_question) +
                         "\n\nSTRUCTURED EVIDENCE:\n" + json.dumps(evidence, ensure_ascii=False)),
        ])
        content = response.content
        narrative = content if isinstance(content, str) else "\n".join(
            block.get("text", "") for block in content
            if isinstance(block, dict) and block.get("type") == "text"
        )
        # No regex-based output blocking or rewriting: the deterministic risk
        # engine owns numbers, while the grounded LLM handles natural language.
        writer({"kind": "procurement_progress", "stage": "summary_completed"})
        return {"messages": [AIMessage(content=narrative)]}
    except Exception:
        return {"messages": [AIMessage(content="The procurement report is available below, but Gemini's explanation failed.")]}


# Guardrail gate + ORIGINAL LLM tool selection / ToolNode routing.
graph = StateGraph(ChatState)
graph.add_node("intent_node", intent_node)
graph.add_node("scope_reply", scope_reply)
graph.add_node("chat_node", chat_node)
graph.add_node("tools", ToolNode(ALL_TOOLS))
graph.add_node("summary_node", summary_node)

graph.add_edge(START, "intent_node")
graph.add_conditional_edges("intent_node", route_by_intent, {
    "scope_reply": "scope_reply", "chat_node": "chat_node"
})
graph.add_edge("scope_reply", END)
graph.add_conditional_edges("chat_node", tools_condition, {
    "tools": "tools", "__end__": END
})
graph.add_conditional_edges("tools", route_after_tools, {
    "summary_node": "summary_node", "chat_node": "chat_node"
})
graph.add_edge("summary_node", END)


conn = sqlite3.connect(database = DB_PATH, check_same_thread=False)
checkpointer = SqliteSaver(conn=conn)
# Keep your existing SQLite checkpointer.
chatbot = graph.compile(checkpointer=checkpointer)

def retrieve_all_threads():
    all_threads = set()
    for checkpoint in checkpointer.list(None): 
        #Checkpointer list is a generator object and can be looped
        #Checkpoint has many variables and thread ids is found inside config dictionary
        #Number of duplicate thread id's generated for each graph in our case is 3(due to 3 super nodes)
        
        all_threads.add(checkpoint.config['configurable']['thread_id']) 

    return (list(all_threads))




##-----------------Helper frontend functions for saving threads table to sqlite-------------##

def get_db_connection():
    conn = sqlite3.connect(DB_PATH, check_same_thread=False)
    conn.execute("""
        CREATE TABLE IF NOT EXISTS thread_titles (
            thread_id TEXT PRIMARY KEY,
            title TEXT NOT NULL,
            updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
        )
    """)
    return conn


def get_thread_titles():
    conn = get_db_connection()
    rows = conn.execute(
        "SELECT thread_id, title FROM thread_titles ORDER BY updated_at DESC"
    ).fetchall()
    conn.close()
    return {row[0]: row[1] for row in rows}


